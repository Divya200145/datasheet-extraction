"""Synthetic vendor datasheet generator (with ground truth).

IMPORTANT: this data is generated by the same author as the parser. Results on it show that
the pipeline behaves as designed on these layouts; they say nothing about real vendor documents.

Four invented vendors, four layouts:
  A  label | value table, metric units (barg, degC, kW)
  B  label-above-value grid, units in the label (psig, degF, hp)
  C  free "Label: value" text lines, MPa / C, no power field
  D  label | value table that uses labels NOT in the vocabulary (held out on purpose:
     the correct behaviour is to flag for review rather than guess)
"""

from __future__ import annotations

import json
import random
from pathlib import Path

from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

SERVICES = [
    "Cooling water circulation", "Amine flash drum", "Boiler feed water", "Condensate return",
    "Lube oil supply", "Fuel gas knock-out", "Process water transfer", "Seal flush",
    "Diesel transfer", "Hot oil circulation", "Firewater booster", "Caustic dosing",
]
MATERIALS = ["CS", "SS304", "SS316", "SS316L"]
KW_CHOICES = [1.5, 2.2, 3.0, 4.0, 5.5, 7.5, 11.0, 15.0, 18.5, 22.0, 30.0, 37.0, 45.0]

MATERIAL_TEXT = {
    "A": {m: m for m in MATERIALS},
    "B": {"CS": "Carbon Steel", "SS304": "Stainless Steel 304", "SS316": "Stainless Steel 316", "SS316L": "Stainless Steel 316L"},
    "C": {"CS": "Carbon steel (A105)", "SS304": "304 stainless", "SS316": "316 stainless", "SS316L": "316L stainless"},
    "D": {m: m for m in MATERIALS},
}
TAG_PREFIX = {"A": ["P"], "B": ["E", "K"], "C": ["V", "T"], "D": ["P", "E"]}


def _make_item(rng: random.Random, layout: str) -> dict:
    tag = f"{rng.choice(TAG_PREFIX[layout])}-{rng.randint(100, 999)}{rng.choice(['', '', 'A', 'B'])}"
    return {
        "layout": layout,
        "tag": tag,
        "service": rng.choice(SERVICES),
        "design_pressure_barg": rng.randint(4, 120) / 2.0,  # multiples of 0.5 barg
        "design_temp_c": float(rng.randrange(40, 355, 5)),
        "material": rng.choice(MATERIALS),
        "power_kw": rng.choice(KW_CHOICES) if layout in ("A", "B") else None,
        "doc_no": f"DS-{rng.randint(1, 9999):04d}",
    }


def _header(c: canvas.Canvas, title: str, doc_no: str) -> None:
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, 740, title)
    c.setFont("Helvetica", 9)
    c.drawString(50, 724, f"Doc No. {doc_no}    Rev B    Page 1 of 1")


def _draw_a(c: canvas.Canvas, it: dict) -> None:
    _header(c, "ACME PUMPS - EQUIPMENT DATA SHEET", it["doc_no"])
    rows = [
        ("Tag Number", it["tag"]),
        ("Service", it["service"]),
        ("Design Pressure", f"{it['design_pressure_barg']:.1f} barg"),
        ("Design Temperature", f"{int(it['design_temp_c'])} °C"),
        ("Material of Construction", MATERIAL_TEXT["A"][it["material"]]),
        ("Motor Power", f"{it['power_kw']:.1f} kW"),
    ]
    y = 690
    for label, value in rows:
        c.rect(50, y - 8, 500, 24)
        c.line(240, y - 8, 240, y + 16)
        c.setFont("Helvetica-Bold", 10)
        c.drawString(58, y, label)
        c.setFont("Helvetica", 10)
        c.drawString(250, y, value)
        y -= 24
    c.setFont("Helvetica", 8)
    c.drawString(50, 500, "Note 1: Performance guaranteed at rated duty point. Hydrotest per vendor standard.")


def _draw_b(c: canvas.Canvas, it: dict) -> None:
    _header(c, "BOREALIS PROCESS EQUIPMENT - ITEM SHEET", it["doc_no"])
    psig = round(it["design_pressure_barg"] * 14.5038)
    degf = round(it["design_temp_c"] * 9 / 5 + 32)
    hp = round(it["power_kw"] / 0.7457)
    blocks = [
        [("Item Code", it["tag"]), ("Duty", it["service"]), ("Rated Power (hp)", str(hp))],
        [("Max Pressure (psig)", str(psig)), ("Max Temp (°F)", str(degf)), ("Body Material", MATERIAL_TEXT["B"][it["material"]])],
    ]
    y = 680
    for block in blocks:
        for col, (label, value) in enumerate(block):
            x = 50 + col * 180
            c.setFont("Helvetica-Bold", 7)
            c.drawString(x, y, label)
            c.setFont("Helvetica", 11)
            c.drawString(x, y - 16, value)
        y -= 60


def _draw_c(c: canvas.Canvas, it: dict) -> None:
    _header(c, "CYGNUS VESSELS LTD - VESSEL DATA", it["doc_no"])
    mpa = it["design_pressure_barg"] / 10.0
    lines = [
        f"Equipment ID: {it['tag']}",
        f"Fluid / Service: {it['service']}",
        f"Design press.: {mpa:.2f} MPa",
        f"Design temp.: {int(it['design_temp_c'])} C",
        f"Shell material: {MATERIAL_TEXT['C'][it['material']]}",
        "Note 2: Vessel supplied complete with nozzles and internals per drawing.",
    ]
    y = 690
    c.setFont("Helvetica", 10)
    for line in lines:
        c.drawString(50, y, line)
        y -= 16


def _draw_d(c: canvas.Canvas, it: dict) -> None:
    _header(c, "DELTA INSTRUMENTS - SPECIFICATION", it["doc_no"])
    rows = [
        ("Position No.", it["tag"]),
        ("Application", it["service"]),
        ("Pmax", f"{it['design_pressure_barg']:.1f} bar"),
        ("Tmax", f"{int(it['design_temp_c'])} C"),
        ("Wetted parts", MATERIAL_TEXT["D"][it["material"]]),
    ]
    y = 690
    for label, value in rows:
        c.setFont("Helvetica-Bold", 10)
        c.drawString(58, y, label)
        c.setFont("Helvetica", 10)
        c.drawString(250, y, value)
        y -= 24


_DRAW = {"A": _draw_a, "B": _draw_b, "C": _draw_c, "D": _draw_d}


def generate_dataset(out_dir: str | Path, n_per_layout: int = 40, seed: int = 7) -> list[dict]:
    """Write PDFs plus truth.json to out_dir and return the ground-truth list."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)
    truth: list[dict] = []
    for layout in "ABCD":
        for i in range(n_per_layout):
            item = _make_item(rng, layout)
            name = f"{layout}_{i:03d}.pdf"
            c = canvas.Canvas(str(out / name), pagesize=letter, invariant=1)
            _DRAW[layout](c, item)
            c.showPage()
            c.save()
            truth.append({"file": name, **item})
    (out / "truth.json").write_text(json.dumps(truth, indent=1, sort_keys=True), encoding="utf-8")
    return truth
