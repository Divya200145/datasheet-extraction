"""Generate the synthetic set, run the pipeline, and write measured results.

Usage: python scripts/evaluate.py [--n 40] [--seed 7] [--runs 10] [--data data/synthetic] [--out results]

Everything reported is computed here from the run; nothing is hard-coded.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from datasheet_extraction import canonical_json, extract_pdf  # noqa: E402
from datasheet_extraction.synth import generate_dataset  # noqa: E402

FIELDS = ["tag", "service", "design_pressure_barg", "design_temp_c", "material", "power_kw"]
# Numeric tolerances come from display rounding in the generated documents (psig and hp are
# shown as integers, degF as an integer), not from parser slack.
TOL = {"design_pressure_barg": 0.05, "design_temp_c": 0.5, "power_kw": 0.5}


def field_correct(field: str, pred, truth) -> bool:
    if truth is None or pred is None:
        return truth is None and pred is None
    if field in TOL:
        return abs(pred - truth) <= TOL[field]
    if field == "service":
        return " ".join(str(pred).split()).casefold() == " ".join(str(truth).split()).casefold()
    return pred == truth


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=40, help="documents per layout")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--runs", type=int, default=10, help="repeat runs for the determinism check")
    ap.add_argument("--data", type=Path, default=Path("data/synthetic"))
    ap.add_argument("--out", type=Path, default=Path("results"))
    args = ap.parse_args()

    truth = generate_dataset(args.data, args.n, args.seed)
    stats: dict[str, dict] = defaultdict(
        lambda: {"docs": 0, "ok": 0, "needs_review": 0, "all_fields_correct": 0, "ok_but_wrong": 0,
                 "field_correct": defaultdict(int), "hallucinated": 0}
    )
    nondeterministic = []

    for item in truth:
        path = args.data / item["file"]
        records = extract_pdf(path)
        rec = records[0]
        s = stats[item["layout"]]
        s["docs"] += 1
        s[rec.status] += 1
        correct = {f: field_correct(f, getattr(rec, f), item[f]) for f in FIELDS}
        for f, ok in correct.items():
            s["field_correct"][f] += ok
            if item[f] is None and getattr(rec, f) is not None:
                s["hallucinated"] += 1
        if all(correct.values()):
            s["all_fields_correct"] += 1
        if rec.status == "ok" and not all(correct.values()):
            s["ok_but_wrong"] += 1  # the dangerous case: confident and wrong

        digests = {hashlib.sha256(canonical_json(extract_pdf(path)).encode()).hexdigest() for _ in range(args.runs)}
        if len(digests) != 1:
            nondeterministic.append(item["file"])

    total_docs = sum(s["docs"] for s in stats.values())
    metrics = {
        "config": {"docs_per_layout": args.n, "seed": args.seed, "determinism_runs": args.runs, "tolerances": TOL},
        "layouts": {
            k: {
                "docs": s["docs"],
                "status_ok": s["ok"],
                "status_needs_review": s["needs_review"],
                "all_fields_correct": s["all_fields_correct"],
                "ok_but_wrong": s["ok_but_wrong"],
                "values_where_truth_is_none": s["hallucinated"],
                "field_accuracy": {f: round(s["field_correct"][f] / s["docs"], 4) for f in FIELDS},
            }
            for k, s in sorted(stats.items())
        },
        "determinism": {
            "documents": total_docs,
            "runs_each": args.runs,
            "documents_with_differing_output": len(nondeterministic),
        },
    }

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "metrics.json").write_text(json.dumps(metrics, indent=2, sort_keys=True) + "\n")

    desc = {"A": "table, metric units", "B": "label-above-value grid, psig/degF/hp", "C": "free 'Label: value' text, MPa",
            "D": "unseen labels (held out on purpose)"}
    lines = [
        "# Evaluation results (synthetic data)",
        "",
        f"Generated by `scripts/evaluate.py` with seed {args.seed}, {args.n} documents per layout. "
        "The documents and the parser were written by the same person, so these numbers show the pipeline "
        "behaves as designed on these layouts. They are **not** an estimate of accuracy on real vendor documents.",
        "",
        "| Layout | Description | Docs | Status ok | Needs review | All fields correct | OK but wrong |",
        "|---|---|---|---|---|---|---|",
    ]
    for k, m in metrics["layouts"].items():
        lines.append(f"| {k} | {desc[k]} | {m['docs']} | {m['status_ok']} | {m['status_needs_review']} | "
                     f"{m['all_fields_correct']} | {m['ok_but_wrong']} |")
    lines += ["", "Per-field accuracy (fraction of documents where the field matched ground truth, within tolerance):", "",
              "| Layout | " + " | ".join(FIELDS) + " |", "|---|" + "---|" * len(FIELDS)]
    for k, m in metrics["layouts"].items():
        lines.append(f"| {k} | " + " | ".join(f"{m['field_accuracy'][f]:.2f}" for f in FIELDS) + " |")
    d = metrics["determinism"]
    lines += [
        "",
        f"Determinism: {d['documents']} documents, each extracted {d['runs_each']} times; "
        f"{d['documents_with_differing_output']} documents produced differing canonical JSON.",
        "",
        f"Numeric tolerances (from display rounding in the generated PDFs): {TOL}.",
        "Layout D uses labels outside the vocabulary; the desired outcome is `needs_review`, never a confident wrong value.",
    ]
    (args.out / "results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    if nondeterministic:
        sys.exit(f"non-deterministic output for: {nondeterministic[:5]}")


if __name__ == "__main__":
    main()
